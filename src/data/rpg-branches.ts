export interface RPGSubChoice {
  id: string;
  label: string;
  dialogueResponse: string;
  endingId: string;
  institutionDelta: number;
  welfareDelta: number;
  budgetDelta: number;
}

export interface RPGChoiceOption {
  id: string;
  label: string;
  stance: 'socialist' | 'capitalist' | 'compromise' | 'bureaucratic';
  dialogueResponse: string; // NPC phản hồi trực tiếp sau khi người chơi chọn bước 1
  institutionDelta: number;
  welfareDelta: number;
  budgetDelta: number; // Tỷ VNĐ
  nextStepPrompt: string; // BƯỚC 2: Câu hỏi/thách thức thứ cấp mở ra từ bước 1
  subOptions: RPGSubChoice[]; // BƯỚC 2: Các lựa chọn chi tiết
  endingId?: string; // Tùy chọn kết cục trực tiếp nếu không qua bước 2
}

export interface RPGSingleEnding {
  id: string;
  title: string;
  badgeLabel: string; // Tên ngắn gọn hiển thị trên đầu NPC trong game
  icon: string;
  category: 'socialist' | 'capitalist' | 'compromise' | 'bureaucratic';
  color: string;
  summary: string;
  socialConsequence: string; // Hệ quả thực tế đối với xã hội & thị trường
  marxistFoundation: string; // Căn cứ trang giáo trình Kinh tế chính trị Mác - Lênin
  institutionScore: number;
  welfareScore: number;
  budgetGain: number;
}

export interface RPGDistrictGrandEnding {
  id: string;
  districtId: 1 | 2 | 3 | 4;
  title: string;
  icon: string;
  badgeCode: string;
  description: string;
  overallEvaluation: string;
}

